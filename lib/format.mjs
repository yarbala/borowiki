// Подписи на русском. Отдельным модулем — чтобы их можно было проверить запуском,
// не запуская при этом всю сборку данных.

export const plural = (n, f) => {
  const m10 = n % 10, m100 = n % 100;
  return m10 === 1 && m100 !== 11 ? f[0] : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? f[1] : f[2];
};

/**
 * «40 минут назад», «5 часов назад», «3 дня назад» — по свежести важен именно час.
 *
 * Часы показываем до двух суток: правило владельца — быть на месте через 2–4 дня,
 * и разница между «35 часов» и «двое суток» для него существенная. Дни округляем
 * вниз, чтобы подпись никогда не отправляла в лес раньше, чем прошло времени.
 */
export function agoText(ms) {
  const minutes = Math.max(0, Math.round(ms / 60_000));
  if (minutes < 60) {
    const n = Math.max(1, minutes);
    return `${n} ${plural(n, ['минуту', 'минуты', 'минут'])} назад`;
  }
  const hours = Math.round(minutes / 60);
  if (hours < 48) return `${hours} ${plural(hours, ['час', 'часа', 'часов'])} назад`;
  const days = Math.floor(hours / 24);
  return `${days} ${plural(days, ['день', 'дня', 'дней'])} назад`;
}
